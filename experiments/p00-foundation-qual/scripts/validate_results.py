#!/usr/bin/env python3
"""Independent, fail-closed validation of the committed qualification bundle.

``validation_results.json`` is generated by this command and is never read as
evidence. Set ``QUAL_RESULTS_ROOT`` for an isolated tamper-negative test.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

RESULTS = Path(os.environ.get("QUAL_RESULTS_ROOT", Path(__file__).resolve().parents[1] / "results"))
REPO = Path(__file__).resolve().parents[3]
FIXTURE = REPO / "experiments" / "p00-foundation-qual" / "fixtures" / "event-v1.json"
FORBIDDEN = re.compile(r"/(?:home|srv|tmp|run)/|(?:username|hostname|serial|secret|capability_bytes)\s*[:=]", re.I)
RESULT_FILES = ("jcs_toolchain_results.json", "ipc_results.json", "sqlite_results.json")


def read_json(name: str) -> object:
    value = json.loads((RESULTS / name).read_text(encoding="utf-8"))
    if FORBIDDEN.search(json.dumps(value, sort_keys=True)):
        raise AssertionError(f"forbidden private field in {name}")
    return value


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def unbox(field: object) -> object:
    return field.get("value") if isinstance(field, dict) and "value" in field else field


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def validate() -> dict:
    provenance = read_json("provenance.json")
    require(isinstance(provenance, dict), "provenance object")
    require(provenance.get("schema") == "companion-p00-qual-results-v1", "provenance schema")
    require(provenance.get("commands") and provenance.get("evidence_ceiling"), "provenance completeness")
    require(provenance.get("execution_date") and provenance.get("timestamp_precision") == "date-only UTC", "honest timestamp")
    oracle_meta = provenance.get("oracle", {})
    require(oracle_meta.get("package") == "canonicalize" and oracle_meta.get("version") == "5.0.0", "oracle package")
    require(oracle_meta.get("npm_integrity") and oracle_meta.get("node_runtime") == "v24.20.0", "oracle identity")
    require(set(provenance.get("result_file_sha256", {})) == set(RESULT_FILES), "result hash manifest scope")
    for name in RESULT_FILES:
        expected = provenance["result_file_sha256"].get(name)
        require(isinstance(expected, str) and re.fullmatch(r"[0-9a-f]{64}", expected) is not None, f"hash manifest {name}")
        require(sha256(RESULTS / name) == expected, f"result hash mismatch: {name}")
    require(provenance.get("fixture_sha256") == sha256(FIXTURE), "fixture hash mismatch")
    evidence_commit = provenance.get("evidence_commit")
    pending_commit = evidence_commit == "PENDING_NARROW_CORRECTION_COMMIT"
    require(pending_commit or (isinstance(evidence_commit, str) and re.fullmatch(r"[0-9a-f]{40}", evidence_commit) is not None), "evidence commit identity")
    ancestry_verified = False if pending_commit else subprocess.run(["git", "merge-base", "--is-ancestor", evidence_commit, "HEAD"], cwd=REPO).returncode == 0
    require(pending_commit or ancestry_verified, "evidence ancestry")

    jcs = read_json("jcs_toolchain_results.json")
    require(jcs.get("oracle", {}).get("package") == "canonicalize@5.0.0", "JCS package")
    require(jcs.get("oracle", {}).get("license") == "Apache-2.0" and jcs.get("oracle", {}).get("node_engine") == ">=22", "JCS metadata")
    require(jcs.get("oracle", {}).get("node_runtime") == "v24.20.0", "JCS runtime")
    require(jcs.get("status") == "PASSED_BOUNDED_PROFILE", "JCS status")
    require(jcs.get("recommendation") == "BLOCKED — MORE EVIDENCE REQUIRED", "toolchain recommendation boundary")
    for key, result in jcs.get("conformance", {}).items():
        require(result is True, f"JCS conformance: {key}")
    parity = jcs.get("behavioral_parity", {})
    require(parity.get("queue_overflow") == "DEFERRED_PHASE_01", "queue overflow")
    for key, result in parity.items():
        if key != "queue_overflow":
            require(result is True, f"behavioral parity: {key}")
    require(jcs.get("rust", {}).get("release_build") is True and int(jcs.get("rust", {}).get("tests_passed", 0)) >= 1, "Rust build/tests")
    require(jcs.get("unsupported_claims_removed") == ["altered_digest_detection", "controlled_shutdown", "no_egress", "rejection_reasons"], "unsupported JCS claims")

    ipc = read_json("ipc_results.json")
    require(ipc.get("status") == "PASSED_BOUNDED_CANDIDATE_MATRIX", "IPC status")
    processes = ipc.get("processes", {})
    runtime_fields = ("roles_started", "independent_children", "producer_ready", "care_ready", "producer_dumpable_prctl", "care_dumpable_prctl", "care_passcred", "pidfd_liveness_generation_bound")
    for key in runtime_fields:
        field = processes.get(key)
        require(unbox(field) is True and isinstance(field, dict) and field.get("evidence_class") in {"RUNTIME_OBSERVED", "KERNEL_OBSERVED"}, f"IPC runtime field: {key}")
    for key in ("producer_endpoint_supervisor_copy_closed", "care_endpoint_supervisor_copy_retained_for_restart", "care_endpoint_supervisor_copy_read", "producer_endpoint_not_in_care", "care_endpoint_not_in_producer", "descriptor_inheritance_closed", "supervisor_trusted_capability_provisioner"):
        field = processes.get(key)
        require(isinstance(field, dict) and field.get("evidence_class") == "CODE_INSPECTED", f"IPC code-inspected field: {key}")
    tests = ipc.get("tests", {})
    valid = tests.get("candidate2_actual_socket_packet", {})
    require(valid.get("accepted") is True and valid.get("duplicate") is False and valid.get("kernel_peer_verified") is True, "IPC valid packet")
    require(tests.get("candidate2_duplicate", {}).get("duplicate") is True, "IPC duplicate")
    for key in ("candidate2_spoofed_field", "candidate2_generation_mismatch", "candidate2_malformed_schema", "candidate2_forbidden_mood_input", "candidate2_old_capability", "stale_generation_after_restart", "old_capability_after_restart"):
        require(tests.get(key, {}).get("accepted") is False, f"IPC rejection: {key}")
    require(tests.get("candidate2_companion_db_absent", {}).get("accepted") is True, "IPC companion-db independence")
    require(tests.get("care_restart_duplicate_redelivery", {}).get("duplicate") is True, "IPC care restart")
    require(tests.get("producer_replacement_new_generation", {}).get("accepted") is True, "IPC producer replacement")
    outage = tests.get("common_sensor_model_outage", {})
    require(outage.get("status") == "degraded" and outage.get("normal_coverage_claimed") is False, "IPC outage semantics")
    old_channel = tests.get("old_channel_after_care_restart", {})
    require(old_channel.get("sent") is False and old_channel.get("errno") == 32 and old_channel.get("name") == "EPIPE", "IPC old-channel failure")
    attacker = tests.get("same_user_sibling_attacks", {})
    require(attacker.get("environment_capability") is False and attacker.get("argv_capability") is False, "IPC capability exposure")
    require(attacker.get("pidfd_getfd") == {"syscall": "pidfd_getfd", "status": "error", "errno": 1, "name": "EPERM"}, "pidfd_getfd result")
    require(attacker.get("proc_fd_open") == {"errno": 13, "name": "EACCES"}, "proc descriptor result")

    sqlite = read_json("sqlite_results.json")
    require(sqlite.get("status") == "PASSED_BOUNDED_MATRIX" and sqlite.get("artifact", {}).get("local_matches_published") is True, "SQLite artifact/status")
    conc = sqlite.get("concurrency", {})
    require(conc.get("before_count") == 5 and conc.get("during_counts") == [5, 5] and conc.get("after_counts") == [6, 6], "SQLite counts")
    require(conc.get("inserted_overlap_row_count") == 1 and conc.get("during_equals_before") is True and conc.get("after_equals_before_plus_one") is True, "SQLite count relations")
    migration = sqlite.get("migration", {})
    for key in ("rejected_before_mutation", "schema_unchanged", "user_version_unchanged", "logical_data_unchanged"):
        require(migration.get(key) is True, f"SQLite migration: {key}")
    disk = sqlite.get("disk_full", {})
    require(disk.get("pre_post_logical_equality") is True and disk.get("integrity") == "ok", "SQLite disk-full")
    backup = sqlite.get("backup_restore", {})
    for key in ("integrity", "schema_digest", "user_version", "ordered_logical_rows_digest", "fresh_directory", "full_equivalence"):
        require(backup.get(key) is True, f"SQLite backup: {key}")
    faults = sqlite.get("fault_vfs", {})
    require(faults.get("status") == "PASSED", "SQLite fault status")
    for name, outcome in faults.get("outcomes", {}).items():
        expected = 70 if name.endswith("_crash") else 69
        require(outcome.get("returncode") == expected and outcome.get("expected_returncode") == expected, f"SQLite fault exit: {name}")
        require(outcome.get("integrity") == "ok" and outcome.get("sync_file_class") and outcome.get("sync_ordinal") == 1, f"SQLite fault metadata: {name}")
        require(outcome.get("pre_existing_state_preserved") is True, f"SQLite pre-existing state: {name}")
        if name.startswith("commit_"):
            require(outcome.get("target_count") in {0, 3} and outcome.get("whole_or_absent") is True, f"SQLite commit atomicity: {name}")
        else:
            require(outcome.get("checkpoint_state_equivalent") is True and outcome.get("logical_state_preserved") is True, f"SQLite checkpoint state: {name}")
    require(faults.get("all_integrity_ok") is True and faults.get("all_atomicity_assertions") is True, "SQLite fault aggregate")
    return {"status": "PASSED", "validator": "validate_results.py", "checked_files": list(RESULT_FILES), "fixture_verified": True, "ancestry_verified": ancestry_verified, "evidence_commit_pending_reconciliation": pending_commit, "circular_validation_input": False}


def main() -> int:
    try:
        result = validate()
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError, KeyError, TypeError, ValueError, AssertionError) as error:
        print(f"VALIDATION FAILED: {error}", file=sys.stderr)
        return 1
    (RESULTS / "validation_results.json").write_text(json.dumps(result, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    print("VALIDATION PASSED: committed qualification result bundle is independently bound")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
